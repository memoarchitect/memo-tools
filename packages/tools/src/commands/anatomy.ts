// ─── memo anatomy generate ───────────────────────────────────────────────────
//
// Write the project's anatomy package from the AnatomySelectors it declares (see
// anatomy/anatomy-generator.ts). The package is the one the project already
// imports, `public import <name>_anatomy_fma::*;`, so the name is read from that
// line, not invented.
//
// Anatomy is reference data, not the project's own content, so it is written as a
// LIBRARY: a package of its own under `memo_packages/<name>-anatomy-fma/`, outside the
// project's `include`. memo-tools finds every package there as a library root, the
// way it finds the MEMO ontology, and the model's import selects it. Its classes are
// then types the model uses — kinds, as the ontology's are — not model elements: no
// project ids, no completeness, no findings. It is deliberately NOT listed under
// `dependencies`: a dependency is a model the project builds on, whose imported
// elements join the model (measured: 746 FMA features became elements that way).
// The descriptor's version is the FMA release plus a digest of the selections
// (`5.1.0-1a2b3c4d`), so a diff shows when the selection changed.
//
// A project that imports the package before it exists would not compile, so a
// missing package is first written empty; then the project is compiled, its
// selectors read, and the package replaced with the union of them.
// ─────────────────────────────────────────────────────────────────────────────

import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import chalk from 'chalk';
import { findProjectRoot, loadProjectSettings } from '@memoarchitect/tools';
import { findSysmlFiles } from '../model/sysml-files.js';
import { withToolchainOverrides } from '../toolchain/schema.js';
import { defaultRegistry } from '../toolchain/default-registry.js';
import { loadProjectModel, Stage1RejectedError } from '../toolchain/project-model.js';
import { isProjectSource } from '../stage2/project-from-api.js';
import {
    ANATOMY_SELECTOR, FMA_INDEX_PATH, emptyAnatomyFacade, readAnatomySelectors, readFmaIndex, renderAnatomy, selectAnatomy,
    type AnatomySelection, type FmaIndex,
} from '../anatomy/anatomy-generator.js';

const GENERATED_MARK = '// GENERATED by `memo anatomy generate`';
const IMPORT_RE = /\bimport\s+([A-Za-z_]\w*_anatomy_fma)::\*/;

export interface AnatomyGenerateResult {
    packageName: string;
    directory: string;
    version: string;
    selectors: number;
    deep: number;
    declared: number;
    files: string[];
    /** Errors the project would have with the new anatomy: names a narrower selection no longer declares. */
    broken: string[];
    /** False when those errors kept the previous anatomy in place. */
    written: boolean;
}

export async function anatomyGenerate(dir: string, options: Record<string, unknown> = {}): Promise<AnatomyGenerateResult> {
    const projectRoot = findProjectRoot(resolve(dir));
    if (!projectRoot) throw new Error('No MEMO project found. A project is located by the `entrypoint` in its `memo.package.yaml`.');

    // The package the project imports, and the dependency that holds it.
    const packageName = findSysmlFiles(projectRoot).map(file => IMPORT_RE.exec(readFileSync(file, 'utf8'))?.[1]).find(Boolean);
    if (!packageName) {
        throw new Error('The project imports no anatomy package. Add `public import <project>_anatomy_fma::*;` to its '
            + 'entrypoint, beside `public import memo_extension_anatomy::*;` and its AnatomySelectors.');
    }
    const libraryName = packageName.replaceAll('_', '-');
    const directory = join(projectRoot, 'memo_packages', libraryName);
    const descriptorPath = join(directory, 'memo.package.yaml');
    if (!existsSync(descriptorPath)) {
        mkdirSync(directory, { recursive: true });
        writeFileSync(descriptorPath, descriptor(libraryName, '0.0.0', undefined, []));
        writeFileSync(join(directory, `${packageName}.sysml`), emptyAnatomyFacade(packageName));
    }

    // The selectors are read from the project as it compiles now, with the anatomy
    // it already has: a compiler that rejects a project hands back no model. So a
    // class is selected and generated before the model names it.
    const config = withToolchainOverrides(loadProjectSettings(projectRoot), options, defaultRegistry);
    let project: Awaited<ReturnType<typeof loadProjectModel>>;
    try {
        project = await loadProjectModel({ projectRoot, config, files: findSysmlFiles(projectRoot), cache: false });
    } catch (error) {
        if (!(error instanceof Stage1RejectedError)) throw error;
        throw new Error(`${error.message}\nThe selectors are read from the project as it compiles with the anatomy it `
            + 'has now. If these errors name anatomy classes the model uses before they are generated, select them, '
            + 'generate, and then use them.');
    }
    const { api, resolution } = project;
    if (!resolution) throw new Error('The project resolved no libraries, so the anatomy extension is not loaded.');
    const isProjectFile = isProjectSource(resolution);
    const selections = readAnatomySelectors(api, isProjectFile);
    if (selections.length === 0) {
        throw new Error(`The project declares no ${ANATOMY_SELECTOR}. Declare one in its entrypoint, e.g. `
            + '`part upperGi :> upperGastrointestinal;`.');
    }

    // The index sits in the package that declares the selector type.
    const selectorDef = api.ofType('PartDefinition').find(d => api.name(d['@id']) === ANATOMY_SELECTOR);
    const selectorFile = selectorDef ? api.absoluteFile(selectorDef['@id']) : undefined;
    const root = selectorFile
        ? [...resolution.selectedRoots, ...resolution.unusedRoots].find(r => selectorFile.startsWith(r.sysmlDir + sep))
        : undefined;
    if (!root) throw new Error(`No ${ANATOMY_SELECTOR} definition found in the project's libraries.`);
    const indexPath = join(root.dir, FMA_INDEX_PATH);
    if (!existsSync(indexPath)) throw new Error(`The anatomy extension at ${root.dir} carries no ${FMA_INDEX_PATH}.`);
    const index = readFmaIndex(indexPath);

    const selected = selectAnatomy(index, selections);
    if (selected.unknown.length) {
        throw new Error('Unknown FMA ids: ' + selected.unknown.map(u => `${u.id} (${u.selector})`).join(', '));
    }
    const files = renderAnatomy(index, selected, packageName, selections);

    // Replace what an earlier run wrote, and nothing else; keep it until the new set compiles.
    const previous = new Map<string, string>();
    for (const entry of readdirSync(directory)) {
        const file = join(directory, entry);
        const text = readFileSync(file, 'utf8');
        if (entry === 'memo.package.yaml' || entry === 'NOTICE.md') {
            previous.set(file, text);
        } else if (entry.endsWith('.sysml') && text.startsWith(GENERATED_MARK)) {
            previous.set(file, text);
            rmSync(file);
        }
    }
    const version = `${index.source.version}-${digest(index, selections)}`;
    for (const [name, content] of files) writeFileSync(join(directory, name), content);
    writeFileSync(descriptorPath, descriptor(libraryName, version, index, selections));
    writeFileSync(join(directory, 'NOTICE.md'), notice(index));

    // A narrower selection can drop a class the model still names. Writing it anyway
    // would leave a project that no longer compiles, from which the selectors cannot be
    // read again, so the previous anatomy is put back unless the caller insists.
    let broken: string[] = [];
    try {
        await loadProjectModel({ projectRoot, config, files: findSysmlFiles(projectRoot), cache: false });
    } catch (error) {
        if (!(error instanceof Stage1RejectedError)) throw error;
        broken = error.diagnostics.filter(d => d.severity === 'error')
            .map(d => `${d.file ? relative(projectRoot, d.file.startsWith('file:') ? fileURLToPath(d.file) : d.file) : '?'}: ${d.message}`);
    }
    const kept = broken.length > 0 && options.force !== true;
    if (kept) {
        for (const name of files.keys()) rmSync(join(directory, name), { force: true });
        for (const [file, text] of previous) writeFileSync(file, text);
    }

    return {
        packageName,
        directory: relative(projectRoot, directory) || '.',
        version,
        selectors: selections.length,
        deep: selected.deep.size,
        declared: selected.emitted.size,
        files: [...files.keys()],
        broken,
        written: !kept,
    };
}

/** The selections in a stable order, hashed with the index they were resolved against. */
function digest(index: FmaIndex, selections: readonly AnatomySelection[]): string {
    const key = JSON.stringify([index.source.version, selections.map(s => [[...s.seeds].sort(), s.partDepth]).sort()]);
    return createHash('sha256').update(key).digest('hex').slice(0, 8);
}

/** The generated package's descriptor: identity and location, as every MEMO package's is. */
function descriptor(name: string, version: string, index: FmaIndex | undefined, selections: readonly AnatomySelection[]): string {
    const lines = [
        '# GENERATED by `memo anatomy generate`: this project\'s anatomy, a library of its own.',
        '# Do not edit: change the project\'s AnatomySelectors and regenerate.',
        ...selections.map(s => `#   ${s.name}: ${s.seeds.join(', ')} (part depth ${s.partDepth})`),
        `name: ${name}`,
        `version: ${version}`,
        `description: Human anatomy this project selects${index ? `, from the ${index.source.title} ${index.source.version}` : ''}`,
        `license: ${index ? 'CC-BY-4.0' : 'MIT'}`,
        'sysmlDir: .',
        '',
    ];
    return lines.join('\n');
}

/** The attribution CC BY 4.0 asks for, beside the content it covers. */
function notice(index: FmaIndex): string {
    const { source } = index;
    return [
        '# Attribution',
        '',
        `The SysML in this directory is derived from the **${source.title}**, release ${source.version}, by the`,
        `**${source.publisher}** (${source.iri}), licensed ${source.licence}.`,
        '',
        `**Changes made:** ${source.modification} It holds only the classes this project's AnatomySelectors`,
        'select, as written by `memo anatomy generate`. The University of Washington does not endorse it.',
        '',
    ].join('\n');
}

export async function anatomyGenerateCommand(dir: string, options: Record<string, unknown>): Promise<void> {
    const result = await anatomyGenerate(dir, options);
    const summary = `${result.selectors} selector(s); ${result.deep} classes with their relations, `
        + `${result.declared} declared in all, in ${result.files.length} files.`;
    if (!result.written) {
        console.log(chalk.red(`✖ ${result.packageName} not changed: the model names anatomy the selectors no longer select.`));
        for (const line of result.broken.slice(0, 20)) console.log(`  ${line}`);
        console.log(chalk.gray(`  Remove those references, or rerun with --force to write it anyway. (${summary})`));
        process.exitCode = 1;
        return;
    }
    console.log(chalk.green(`✔ ${result.packageName} ${result.version}`) + chalk.gray(` in ${result.directory}`));
    console.log(`  ${summary}`);
    if (result.broken.length) {
        console.log(chalk.yellow(`⚠ Written with --force; the project no longer compiles (${result.broken.length} error(s)):`));
        for (const line of result.broken.slice(0, 20)) console.log(`  ${line}`);
        process.exitCode = 1;
    }
}
