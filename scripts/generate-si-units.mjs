#!/usr/bin/env node
// ─── SI unit conversions, read from the vendored SysML v2 library ────────────
//
// The calculation evaluator multiplies and adds quantities (`600 [euro/hour] * 30 [minute]`), which
// needs each unit's conversion to its base unit. The library declares them
// (`attribute <min> minute : DurationUnit { … ConversionByConvention { referenceUnit = s; conversionFactor = 60; } }`)
// and the compiler's handoff does not carry library elements, so the table is read from the pinned
// corpus here, the way the metamodel is read from the ecore, and committed.
//
//   node scripts/generate-si-units.mjs
// ─────────────────────────────────────────────────────────────────────────────

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dir = resolve(here, '../corpus/sysml-v2-release/sysml.library/Domain Libraries/Quantities and Units');
const si = readFileSync(resolve(dir, 'SI.sysml'), 'utf8');
const prefixes = readFileSync(resolve(dir, 'SIPrefixes.sysml'), 'utf8');

const name = '(?:\'[^\']+\'|[A-Za-z_]\\w*)';
const lineRe = new RegExp(`^\\s*attribute\\s*<(${name})>\\s*(${name})\\s*:\\s*(\\w+)(.*)$`);
const unquote = (n) => n.replace(/^'|'$/g, '');
const units = {};
for (const line of si.split('\n')) {
    const m = lineRe.exec(line);
    if (!m) continue;
    const [, symbol, longName, dim, tail] = m;
    const entry = { dim };
    const convention = /ConversionByConvention\s*\{[^}]*referenceUnit\s*=\s*([^;]+);[^}]*conversionFactor\s*=\s*([^;]+);/.exec(tail);
    const prefix = /ConversionByPrefix\s*\{[^}]*prefix\s*=\s*([^;]+);[^}]*referenceUnit\s*=\s*([^;]+);/.exec(tail);
    if (convention) { entry.ref = convention[1].trim(); entry.factor = Number(convention[2].trim()); }
    else if (prefix) { entry.prefix = prefix[1].trim(); entry.ref = prefix[2].trim(); }
    else if (/^\s*=/.test(tail)) continue; // a derived unit written as an expression: not a conversion
    units[unquote(symbol)] = entry;
    units[unquote(longName)] = { ...entry, alias: unquote(symbol) };
}
const prefixTable = {};
for (const m of prefixes.matchAll(/attribute\s+(\w+)\s*:\s*UnitPrefix\s*\{[^}]*conversionFactor\s*=\s*([^;]+);/g)) {
    // a factor written as a power (`2**10`) is read as one; anything else that is not a number is left out
    const text = m[2].trim().replace(/\s+/g, '');
    const power = /^(\d+(?:\.\d+)?)(?:\*\*|\^)(-?\d+)$/.exec(text);
    const value = power ? Number(power[1]) ** Number(power[2]) : Number(text);
    if (Number.isFinite(value)) prefixTable[m[1]] = value;
}

const out = `// GENERATED by scripts/generate-si-units.mjs from the vendored SysML v2 library (SI.sysml, SIPrefixes.sysml).
// Do not edit; regenerate.

export interface SiUnit {
    /** The library's unit definition (\`DurationUnit\`): units of one definition are of one quantity. */
    dim: string;
    /** The unit it is defined in terms of, with the factor to it (or the prefix applied to it). */
    ref?: string;
    factor?: number;
    prefix?: string;
    /** The symbol, on an entry that is the long name. */
    alias?: string;
}

export const SI_UNITS: Readonly<Record<string, SiUnit>> = ${JSON.stringify(units, null, 4)};

export const SI_PREFIXES: Readonly<Record<string, number>> = ${JSON.stringify(prefixTable, null, 4)};
`;
writeFileSync(resolve(here, '../packages/tools/src/analysis/calc/generated/si-units.ts'), out);
console.log(`${Object.keys(units).length} unit names, ${Object.keys(prefixTable).length} prefixes`);
