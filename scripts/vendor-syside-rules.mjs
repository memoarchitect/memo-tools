#!/usr/bin/env node
// ─── Vendor `syside rule list` as the B4 checklist ───────────────────────────
//
// Plan §5.1.2: do not invent a parallel MEMO numbering for rules Syside already
// names. `syside rule list` publishes 151 stable kebab-case codes, and B4 is
// scored against them, keeping the code strings so a project's suppressions
// survive the engine swap.
//
// **Why this is vendored rather than queried.** §1.3 rule 1 — a default install
// and the full CI suite pass with zero external tools. A scoreboard that shells
// out to `syside` would make the suite depend on a proprietary binary being
// installed, and would give a different answer on a machine with a different
// Syside version. So the list is a committed snapshot with its version
// recorded, exactly like the corpus.
//
// Run this when the Syside pin moves. `--check` reports drift without writing,
// and is a no-op where `syside` is not installed — which is most CI machines,
// and is the point.
// ─────────────────────────────────────────────────────────────────────────────

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const OUTPUT = resolve(root, 'packages/tools/src/conformance/generated/syside-rules.ts');

function syside(args) {
    return execFileSync('syside', args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
}

/**
 * Parse the two-column listing.
 *
 * A code starts at column zero; its description wraps onto indented
 * continuation lines. Nothing else appears in the output.
 */
function parseRules(text) {
    const rules = [];
    for (const line of text.split('\n')) {
        const declaration = /^([a-z][a-z0-9-]*)\s\s+(.*)$/.exec(line);
        if (declaration) {
            rules.push({ code: declaration[1], description: declaration[2].trim() });
            continue;
        }
        if (/^\s+\S/.test(line) && rules.length > 0) {
            rules[rules.length - 1].description += ` ${line.trim()}`;
        }
    }
    return rules;
}

function build() {
    const version = syside(['--version']).trim();
    const all = parseRules(syside(['rule', 'list']));
    const kerml = new Set(parseRules(syside(['rule', 'list', '-k'])).map(rule => rule.code));
    const sysml = new Set(parseRules(syside(['rule', 'list', '-s'])).map(rule => rule.code));

    const rules = all
        .map(rule => ({
            code: rule.code,
            description: rule.description.replace(/\s+/g, ' ').trim(),
            grammars: [kerml.has(rule.code) ? 'kerml' : undefined, sysml.has(rule.code) ? 'sysml' : undefined].filter(Boolean),
        }))
        .sort((a, b) => (a.code < b.code ? -1 : 1));

    const unclassified = rules.filter(rule => rule.grammars.length === 0).map(rule => rule.code);
    if (unclassified.length > 0) {
        throw new Error(`${unclassified.length} rule(s) in neither the KerML nor the SysML list: ${unclassified.join(', ')}`);
    }

    return `// GENERATED by scripts/vendor-syside-rules.mjs. DO NOT EDIT.
//
// \`${version}\` — \`syside rule list\`, vendored so the B4 scoreboard needs no
// external tool (plan §1.3 rule 1, §5.1.2). Re-run the script when the Syside
// pin moves; the codes are Syside's and are kept verbatim.

export const SYSIDE_VERSION = ${JSON.stringify(version)};

export interface SysideRule {
    /** Stable kebab-case code, used verbatim as MEMO's rule code. */
    code: string;
    description: string;
    /** Which of Syside's two rule lists publish it. */
    grammars: ('kerml' | 'sysml')[];
}

export const SYSIDE_RULES: readonly SysideRule[] = ${JSON.stringify(rules, null, 4)};
`;
}

let generated;
try {
    generated = build();
} catch (error) {
    if (error?.code === 'ENOENT') {
        console.log('syside is not on PATH; leaving the vendored rule list as it is.');
        process.exit(0);
    }
    throw error;
}

if (process.argv.includes('--check')) {
    if (readFileSync(OUTPUT, 'utf8') !== generated) {
        throw new Error(
            'The vendored Syside rule list differs from what this `syside` reports. '
            + 'Re-run `node scripts/vendor-syside-rules.mjs` and review the diff — the checklist moved.',
        );
    }
    console.log('Vendored Syside rule list matches the installed syside.');
} else {
    writeFileSync(OUTPUT, generated);
    console.log(`Wrote ${OUTPUT}`);
}
